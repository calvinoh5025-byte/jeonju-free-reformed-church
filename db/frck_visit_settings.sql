-- 심방 일정 설정 테이블(직분자 공용 비밀번호의 암호화된 값 저장). Supabase SQL Editor에서 한 번만 실행합니다.
-- 비밀번호 원문은 저장하지 않습니다. 서버(service_role)만 접근하고, 성도·로그인 사용자는 DB에 직접 접근할 수 없습니다.
begin;

create table if not exists public.frck_visit_settings (
  key text primary key check (char_length(key) between 1 and 60),
  value text not null,
  updated_at timestamptz not null default now()
);

alter table public.frck_visit_settings enable row level security;
revoke all on table public.frck_visit_settings from public, anon, authenticated;
grant select, insert, update, delete on table public.frck_visit_settings to service_role;

-- 로그인 기록: 관리자가 낯선 이름이 로그인했는지 확인하는 용도입니다. (비밀번호는 저장하지 않습니다)
create table if not exists public.frck_visit_logins (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 50),
  role text not null check (role in ('admin', 'staff')),
  created_at timestamptz not null default now()
);

create index if not exists frck_visit_logins_created_idx on public.frck_visit_logins (created_at desc);

alter table public.frck_visit_logins enable row level security;
revoke all on table public.frck_visit_logins from public, anon, authenticated;
grant select, insert, update, delete on table public.frck_visit_logins to service_role;
grant usage, select on sequence public.frck_visit_logins_id_seq to service_role;

commit;
