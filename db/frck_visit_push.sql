-- 심방 일정 푸시 알림 테이블. Supabase SQL Editor에서 한 번만 실행합니다. (여러 번 실행해도 안전)
-- 이메일·이름·전화번호는 저장하지 않습니다. 알림을 받기로 한 "기기(브라우저)의 알림 주소"만 저장합니다.
-- 서버(service_role)만 읽고 쓰며, 성도·로그인 사용자는 DB에 직접 접근할 수 없습니다.
begin;

create table if not exists public.frck_visit_push_subscriptions (
  id bigint generated by default as identity primary key,
  endpoint text not null unique check (char_length(endpoint) between 20 and 1000),
  p256dh text not null check (char_length(p256dh) between 20 and 200),
  auth text not null check (char_length(auth) between 10 and 100),
  -- 받고 싶은 심방 종류. 기본은 전부.
  kinds text[] not null default '{elder,deacon,special}',
  failures int not null default 0,
  last_sent_at timestamptz,
  created_at timestamptz not null default now()
);

-- 같은 알림이 두 번 가지 않게 보낸 기록을 남깁니다.
create table if not exists public.frck_visit_push_deliveries (
  id bigint generated by default as identity primary key,
  subscription_id bigint not null references public.frck_visit_push_subscriptions (id) on delete cascade,
  visit_id bigint not null references public.frck_visits (id) on delete cascade,
  reminder text not null check (reminder in ('eve', 'morning', 'cancel', 'change')),
  starts_at_sent timestamptz not null,
  created_at timestamptz not null default now(),
  unique (subscription_id, visit_id, reminder, starts_at_sent)
);

-- 알림 신청 남용 방지용 요청 기록(며칠 뒤 자동 삭제됩니다).
create table if not exists public.frck_visit_push_requests (
  id bigint generated by default as identity primary key,
  key text not null,
  created_at timestamptz not null default now()
);

create index if not exists frck_visit_push_requests_key_idx on public.frck_visit_push_requests (key, created_at desc);

alter table public.frck_visit_push_subscriptions enable row level security;
alter table public.frck_visit_push_deliveries enable row level security;
alter table public.frck_visit_push_requests enable row level security;

revoke all on table public.frck_visit_push_subscriptions, public.frck_visit_push_deliveries, public.frck_visit_push_requests from public, anon, authenticated;
grant select, insert, update, delete on table public.frck_visit_push_subscriptions, public.frck_visit_push_deliveries, public.frck_visit_push_requests to service_role;
grant usage, select on sequence public.frck_visit_push_subscriptions_id_seq, public.frck_visit_push_deliveries_id_seq, public.frck_visit_push_requests_id_seq to service_role;

commit;

-- 새 테이블을 바로 쓸 수 있게 Supabase에 알립니다.
notify pgrst, 'reload schema';
