-- 회원가입 화면은 없습니다. 관리자가 관리 화면에서 장로·집사 계정을 등록합니다.
-- 비밀번호 원문은 저장하지 않고 암호화된 값(password_hash)만 저장합니다. 서버(service_role)만 접근합니다.
begin;

create table if not exists public.frck_visit_staff (
  id bigint generated by default as identity primary key,
  email text not null unique check (email = lower(btrim(email)) and char_length(email) between 3 and 200),
  name text not null check (char_length(btrim(name)) between 1 and 50),
  role text not null check (role in ('elder', 'deacon')),
  password_hash text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.frck_visit_staff enable row level security;
revoke all on table public.frck_visit_staff from public, anon, authenticated;
grant select, insert, update, delete on table public.frck_visit_staff to service_role;
grant usage, select on sequence public.frck_visit_staff_id_seq to service_role;

commit;
