-- 심방 일정 테이블. Supabase SQL Editor에서 한 번만 실행합니다. (여러 번 실행해도 안전)
-- 성도·로그인 사용자 모두 DB에 직접 접근할 수 없고, 서버(service_role)만 읽고 씁니다.
-- 공개 화면에는 서버 API(/api/visit-slots)가 id, 날짜·시간, 종류, 목사 동행, 완료 여부만 내려줍니다.
begin;

create table if not exists public.frck_visits (
  id bigint generated by default as identity primary key,
  starts_at timestamptz not null,
  kind text not null default 'elder' check (kind in ('elder', 'deacon')),
  pastor boolean not null default false,
  status text not null default 'scheduled' check (status in ('scheduled', 'done', 'cancelled')),
  -- 아래는 비공개 정보입니다. 공개 API는 절대 읽지 않습니다.
  household text check (household is null or char_length(household) <= 100),
  elder_name text check (elder_name is null or char_length(elder_name) <= 100),
  memo text check (memo is null or char_length(memo) <= 2000),
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists frck_visits_starts_at_idx on public.frck_visits (starts_at);

alter table public.frck_visits enable row level security;
revoke all on table public.frck_visits from public, anon, authenticated;
grant select, insert, update, delete on table public.frck_visits to service_role;
grant usage, select on sequence public.frck_visits_id_seq to service_role;

commit;

